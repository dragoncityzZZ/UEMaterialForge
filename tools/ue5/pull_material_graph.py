def warn(message: str) -> None:
    unreal.log_warning(f"[MaterialForge pull] {message}")


def log(message: str) -> None:
    unreal.log(f"[MaterialForge pull] {message}")


def enum_name(value: Any, fallback: str) -> str:
    if value is None:
        return fallback
    text = str(value)
    if "." in text:
        text = text.rsplit(".", 1)[-1]
    return text or fallback


def class_name(expression: Any) -> str:
    try:
        return expression.get_class().get_name()
    except Exception:
        return type(expression).__name__


def get_property(expression: Any, name: str, fallback: Any = None) -> Any:
    try:
        value = expression.get_editor_property(name)
        return fallback if value is None else value
    except Exception:
        return fallback


def color_to_list(value: Any, count: int = 4) -> list[float]:
    if value is None:
        return [0.0] * count
    result = []
    for component in ("r", "g", "b", "a"):
        try:
            result.append(float(getattr(value, component)))
        except Exception:
            result.append(0.0)
    return result[:count]


def asset_path(asset: Any) -> str:
    if asset is None:
        return ""
    try:
        path = str(asset.get_path_name())
    except Exception:
        path = str(asset)
    return path.split(".", 1)[0] if path.startswith("/Game/") else path


def load_texture_inverse(path: Optional[str]) -> dict[str, str]:
    if not path:
        return {}
    try:
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
    except Exception as exc:  # noqa: BLE001
        warn(f"Could not read texture map: {exc}")
        return {}
    inverse: dict[str, str] = {}
    for source, ue_path in payload.items():
        if isinstance(source, str) and isinstance(ue_path, str):
            inverse[ue_path.split(".", 1)[0].lower()] = source
    return inverse


def expression_input_source(expression: Any, input_name: str) -> Any:
    library = getattr(unreal, "MaterialEditingLibrary", None)
    if library is None:
        return None
    getter = getattr(library, "get_input_node", None)
    if getter is not None:
        try:
            return getter(expression, input_name)
        except Exception:
            pass
    # Older UE5 Python builds expose the input list instead of a named lookup.
    lister = getattr(library, "get_material_expression_inputs", None)
    if lister is not None:
        try:
            for entry in lister(expression):
                name = getattr(entry, "input_name", None)
                if name is None:
                    name = getattr(entry, "name", None)
                if normalize_name(str(name)) == normalize_name(input_name):
                    return getattr(entry, "expression", None)
        except Exception:
            pass
    return None


def material_property_source(material: Any, property_value: Any) -> Any:
    library = getattr(unreal, "MaterialEditingLibrary", None)
    if library is None:
        return None
    for method_name in ("get_material_property_input_node",
                        "get_material_property_input"):
        method = getattr(library, method_name, None)
        if method is None:
            continue
        try:
            value = method(material, property_value)
            if value is not None:
                return value
        except Exception:
            continue
    return None


def load_catalog(path: str) -> tuple[dict[str, dict[str, Any]], dict[str, list[str]]]:
    payload = json.loads(Path(path).read_text(encoding="utf-8"))
    by_type: dict[str, dict[str, Any]] = {}
    by_ue: dict[str, list[str]] = {}
    for node in payload.get("nodes", []):
        if not isinstance(node, dict):
            continue
        node_type = str(node.get("type", ""))
        if not node_type:
            continue
        by_type[node_type] = node
        ue_class = str(node.get("ueClass", ""))
        if ue_class:
            by_ue.setdefault(ue_class, []).append(node_type)
    return by_type, by_ue


def map_type(ue_class: str, by_ue: dict[str, list[str]]) -> Optional[str]:
    candidates = by_ue.get(ue_class, [])
    if not candidates:
        return None
    if len(candidates) == 1:
        return candidates[0]
    # Prefer the canonical expression type over the parameter/output variants.
    for candidate in candidates:
        if candidate == ue_class.replace("MaterialExpression", ""):
            return candidate
    return candidates[0]


def normalize_name(name: str) -> str:
    return "".join(ch for ch in name.lower() if ch.isalnum())


def map_pin(catalog: dict[str, Any], requested: str) -> Optional[str]:
    pins = catalog.get("inputs", [])
    if not pins:
        return None
    normalized = normalize_name(requested)
    for pin in pins:
        if normalize_name(str(pin.get("name", ""))) == normalized:
            return str(pin["name"])
    aliases = {
        "uvs": ("uvs", "uv", "coordinates"),
        "coordinates": ("coordinates", "uvs", "uv"),
        "texture": ("texture", "textureobject", "tex"),
        "input": ("input", "value"),
        "value": ("value", "input"),
        "a": ("a",),
        "b": ("b",),
        "alpha": ("alpha", "opacity", "a"),
    }
    for alias in aliases.get(normalized, ()):
        for pin in pins:
            if normalize_name(str(pin.get("name", ""))) == alias:
                return str(pin["name"])
    if len(pins) == 1:
        return str(pins[0]["name"])
    return None


def default_output(catalog: dict[str, Any], prefer_rgb: bool = False) -> Optional[str]:
    outputs = catalog.get("outputs", [])
    if not outputs:
        return None
    if prefer_rgb:
        for preferred in ("RGB", "RGBA"):
            for pin in outputs:
                if pin.get("name") == preferred:
                    return str(preferred)
    return str(outputs[0]["name"])


def make_pins(node_type: str, catalog: dict[str, Any], next_pin: list[int]) -> list[dict[str, Any]]:
    pins = []
    for direction, key in (("input", "inputs"), ("output", "outputs")):
        for pin in catalog.get(key, []):
            pins.append(
                {
                    "id": next_pin[0],
                    "name": pin.get("name", ""),
                    "direction": direction,
                    "type": pin.get("type", "Float"),
                }
            )
            next_pin[0] += 1
    return pins


def expression_properties(node_type: str, expression: Any,
                          textures: dict[str, str]) -> dict[str, Any]:
    props: dict[str, Any] = {}
    if node_type == "Constant":
        props["value"] = float(get_property(expression, "r", 0.0))
    elif node_type == "Constant2Vector":
        props["value"] = [float(get_property(expression, "r", 0.0)),
                          float(get_property(expression, "g", 0.0))]
    elif node_type in ("Constant3Vector", "Constant4Vector"):
        props["value"] = color_to_list(get_property(expression, "constant"), 4)
    elif node_type == "ScalarParameter":
        props["parameterName"] = str(get_property(expression, "parameter_name", "Value"))
        props["value"] = float(get_property(expression, "default_value", 0.0))
    elif node_type == "VectorParameter":
        props["parameterName"] = str(get_property(expression, "parameter_name", "Color"))
        props["value"] = color_to_list(get_property(expression, "default_value"), 4)
    elif node_type in ("TextureObject", "TextureObjectParameter", "TextureSampleParameter2D"):
        texture = get_property(expression, "texture")
        ue_path = asset_path(texture)
        props["texture"] = textures.get(ue_path.lower(), ue_path)
        parameter_name = get_property(expression, "parameter_name")
        if parameter_name is not None:
            props["parameterName"] = str(parameter_name)
    elif node_type == "TextureSample":
        texture = get_property(expression, "texture")
        ue_path = asset_path(texture)
        # TextureSample has no texture property in MaterialForge; the importer
        # resolves a TextureObject link. Emit the path as a TextureObject child.
        props["texture"] = textures.get(ue_path.lower(), ue_path)
    elif node_type == "TextureCoordinate":
        props["uTiling"] = float(get_property(expression, "u_tiling", 1.0))
        props["vTiling"] = float(get_property(expression, "v_tiling", 1.0))
    elif node_type == "Panner":
        props["speed"] = [float(get_property(expression, "speed_x", 0.0)),
                          float(get_property(expression, "speed_y", 0.0))]
    elif node_type == "Rotator":
        props["center"] = [float(get_property(expression, "center_x", 0.5)),
                           float(get_property(expression, "center_y", 0.5))]
        props["speed"] = float(get_property(expression, "speed", 0.1))
    elif node_type == "Fresnel":
        props["exponent"] = float(get_property(expression, "exponent", 5.0))
        props["baseReflectFraction"] = float(
            get_property(expression, "base_reflect_fraction", 0.04))
    elif node_type == "Comment":
        props["text"] = str(get_property(expression, "text", "Comment"))
    return props


def material_settings(material: Any, name: str) -> dict[str, Any]:
    def enum_value(prop: str) -> Any:
        return get_property(material, prop)

    return {
        "name": name,
        "domain": DOMAIN_NAMES.get(enum_name(enum_value("material_domain"), "MD_SURFACE"),
                                     "Surface"),
        "blendMode": BLEND_NAMES.get(enum_name(enum_value("blend_mode"), "BLEND_OPAQUE"),
                                      "Opaque"),
        "shadingModel": SHADING_NAMES.get(enum_name(enum_value("shading_model"),
                                                     "MSM_DEFAULT_LIT"), "DefaultLit"),
        "translucencyLightingMode": "SurfaceForwardShading",
        "twoSided": bool(get_property(material, "two_sided", False)),
        "ditheredLodTransition": bool(get_property(material, "dithered_lod_transition", False)),
        "castDynamicShadowAsMasked": bool(
            get_property(material, "cast_dynamic_shadow_as_masked", False)),
        "useEmissiveForStaticLighting": bool(
            get_property(material, "use_emissive_for_static_lighting", False)),
        "opacityMaskClip": float(get_property(material, "opacity_mask_clip_value", 0.333)),
    }


def pull(material_path: str, output_path: str, catalog_path: str,
         texture_map_path: Optional[str], dry_run: bool) -> int:
    if unreal is None and not dry_run:
        print("This script must run inside the Unreal Engine 5 editor Python environment.",
              file=sys.stderr)
        return 2
    by_type, by_ue = load_catalog(catalog_path)
    textures = load_texture_inverse(texture_map_path)
    if unreal is None:
        print(f"Catalog loaded: {len(by_type)} node types. UE runtime is not available.")
        return 0

    material = unreal.EditorAssetLibrary.load_asset(material_path)
    if material is None:
        print(f"Could not load material: {material_path}", file=sys.stderr)
        return 1
    material_name = str(getattr(material, "get_name", lambda: "M_MaterialForge")())
    settings = material_settings(material, material_name)

    expressions = list(unreal.MaterialEditingLibrary.get_material_expressions(material))
    output_expressions = [e for e in expressions
                          if class_name(e) == "MaterialExpressionMaterialOutput"]
    expressions = [e for e in expressions if class_name(e) != "MaterialExpressionMaterialOutput"]

    nodes: list[dict[str, Any]] = []
    node_for_expr: dict[Any, dict[str, Any]] = {}
    expression_node_type: dict[Any, str] = {}
    next_node = [2]
    next_pin = [1]
    skipped: list[str] = []

    # Material Output node (id 1).
    output_catalog = by_type.get("MaterialOutput")
    if output_catalog is None:
        print("Node catalog is missing MaterialOutput.", file=sys.stderr)
        return 1
    output_node = {
        "id": 1,
        "type": "MaterialOutput",
        "ueClass": output_catalog.get("ueClass", "MaterialExpressionMaterialOutput"),
        "category": "Output",
        "position": {"x": 700.0, "y": 0.0},
        "properties": {},
        "pins": make_pins("MaterialOutput", output_catalog, next_pin),
    }
    nodes.append(output_node)
    pin_name_to_id = {(1, pin["name"], pin["direction"]): pin["id"]
                      for pin in output_node["pins"]}

    for expression in expressions:
        ue_class = class_name(expression)
        node_type = map_type(ue_class, by_ue)
        if node_type is None:
            skipped.append(ue_class)
            continue
        catalog = by_type[node_type]
        node_id = next_node[0]
        next_node[0] += 1
        node_properties = expression_properties(node_type, expression, textures)
        texture_path = str(node_properties.get("texture", ""))
        node = {
            "id": node_id,
            "type": node_type,
            "ueClass": ue_class,
            "category": catalog.get("category", "Unknown"),
            "position": {
                "x": float(get_property(expression, "material_expression_editor_x", 0.0)),
                "y": float(get_property(expression, "material_expression_editor_y", 0.0)),
            },
            "properties": {
                key: value for key, value in node_properties.items()
                if any(prop.get("key") == key for prop in catalog.get("properties", []))
            },
            "pins": make_pins(node_type, catalog, next_pin),
        }
        if node_type == "TextureSample" and texture_path:
            texture_id = next_node[0]
            next_node[0] += 1
            texture_catalog = by_type.get("TextureObject")
            if texture_catalog:
                texture_node = {
                    "id": texture_id,
                    "type": "TextureObject",
                    "ueClass": texture_catalog.get("ueClass", "MaterialExpressionTextureObject"),
                    "category": "Textures",
                    "position": {"x": node["position"]["x"] - 220.0,
                                 "y": node["position"]["y"] + 80.0},
                    "properties": {"texture": texture_path},
                    "pins": make_pins("TextureObject", texture_catalog, next_pin),
                }
                for pin in texture_node["pins"]:
                    pin_name_to_id[(texture_id, pin["name"], pin["direction"])] = pin["id"]
                nodes.append(texture_node)
                texture_node_for_sample = texture_id
            else:
                texture_node_for_sample = None
        else:
            texture_node_for_sample = None
        for pin in node["pins"]:
            pin_name_to_id[(node_id, pin["name"], pin["direction"])] = pin["id"]
        nodes.append(node)
        node_for_expr[expression] = node
        expression_node_type[expression] = node_type
        node.setdefault("textureObjectId", texture_node_for_sample)

    links: list[dict[str, Any]] = []
    link_id = [1]

    def add_link(source_node_id: int, source_pin: str,
                 target_node_id: int, target_pin: str) -> None:
        source_pin_id = pin_name_to_id.get((source_node_id, source_pin, "output"))
        target_pin_id = pin_name_to_id.get((target_node_id, target_pin, "input"))
        if source_pin_id is None or target_pin_id is None:
            return
        if any(link["fromPin"] == source_pin_id and link["toPin"] == target_pin_id
               for link in links):
            return
        links.append({
            "id": link_id[0],
            "fromNode": source_node_id,
            "fromPin": source_pin_id,
            "fromPinName": source_pin,
            "toNode": target_node_id,
            "toPin": target_pin_id,
            "toPinName": target_pin,
        })
        link_id[0] += 1

    for expression, node in node_for_expr.items():
        catalog = by_type[node["type"]]
        try:
            input_names = list(
                unreal.MaterialEditingLibrary.get_material_expression_input_names(expression))
        except Exception as exc:  # noqa: BLE001
            warn(f"Could not read inputs for {node['type']}: {exc}")
            continue
        for ue_input in input_names:
            source = expression_input_source(expression, str(ue_input))
            if source is None or source not in node_for_expr:
                continue
            target_pin = map_pin(catalog, str(ue_input))
            if target_pin is None:
                warn(f"No MaterialForge input for {node['type']}.{ue_input}")
                continue
            source_node = node_for_expr[source]
            source_catalog = by_type[source_node["type"]]
            source_pin = default_output(source_catalog, prefer_rgb=True)
            if source_pin is None:
                continue
            add_link(source_node["id"], source_pin, node["id"], target_pin)
        # TextureSample's texture property is represented by a child node.
        texture_child = node.get("textureObjectId")
        if texture_child:
            child_catalog = by_type.get("TextureObject")
            child_pin = default_output(child_catalog) if child_catalog else None
            sample_catalog = by_type[node["type"]]
            sample_texture_input = map_pin(sample_catalog, "Texture")
            if child_pin and sample_texture_input:
                add_link(texture_child, child_pin, node["id"], sample_texture_input)

    # Material property outputs.
    for mf_pin, ue_enum in MATERIAL_PROPERTIES.items():
        enum_value = getattr(unreal.MaterialProperty, ue_enum, None)
        if enum_value is None:
            continue
        source = material_property_source(material, enum_value)
        if source is None or source not in node_for_expr:
            continue
        source_node = node_for_expr[source]
        source_catalog = by_type[source_node["type"]]
        prefer_rgb = mf_pin in ("Base Color", "Emissive Color", "Subsurface Color")
        source_pin = default_output(source_catalog, prefer_rgb=prefer_rgb)
        if source_pin:
            add_link(source_node["id"], source_pin, 1, mf_pin)

    document = {
        "schema": SCHEMA_ID,
        "version": SCHEMA_VERSION,
        "generator": "MaterialForge UE5 pull bridge",
        "engine": "Unreal Engine 5",
        "material": settings,
        "nodes": nodes,
        "links": links,
        "source": {
            "ueMaterial": material_path,
            "ueClassCount": len(expressions),
            "skippedClasses": sorted(set(skipped)),
        },
    }
    if output_path:
        Path(output_path).write_text(json.dumps(document, indent=2), encoding="utf-8")
    if dry_run:
        print(json.dumps({"material": settings, "nodes": len(nodes), "links": len(links),
                          "skipped": sorted(set(skipped))}, indent=2))
    else:
        log(f"Pulled {len(nodes)} nodes and {len(links)} links -> {output_path}")
    return 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Pull a UE5 material into MaterialForge JSON.")
    parser.add_argument("--material", default="", help="UE content path, e.g. /Game/Materials/M_Test")
    parser.add_argument("--out", default="", help="Destination MaterialForge JSON path.")
    parser.add_argument("--catalog",
                        default=str(Path(__file__).with_name("node_catalog.json")),
                        help="node_catalog.json generated by MaterialForge.")
    parser.add_argument("--texture-map", default=None,
                        help="Optional MaterialForge texture path -> UE asset map.")
    parser.add_argument("--dry-run", action="store_true", help="Validate and print the plan.")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if not args.material and not args.dry_run:
        print("--material is required.", file=sys.stderr)
        return 2
    try:
        return pull(args.material, args.out, args.catalog, args.texture_map, args.dry_run)
    except Exception as exc:  # noqa: BLE001
        print(f"Pull failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())

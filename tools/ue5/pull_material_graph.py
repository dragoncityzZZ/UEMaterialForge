#!/usr/bin/env python3
"""Unreal Engine 5 -> MaterialForge pull bridge.

Run this inside the UE5 editor Python environment (or through
`UnrealEditor-Cmd.exe ... -run=pythonscript -script=...`) to serialize an
existing material graph into the `materialforge.ue5.material` JSON format.

    py "C:/path/to/tools/ue5/pull_material_graph.py" \
       --material /Game/Materials/M_Example \
       --out "C:/path/to/M_Example.pulled.json" \
       --texture-map "C:/path/to/tools/ue5/texture_map.json"

The script uses `unreal.MaterialEditingLibrary` for expression traversal and
maps expression classes through `tools/ue5/node_catalog.json` (generated by
MaterialForge with `--export-node-catalog`). Unsupported expressions are
reported as warnings and omitted; their links are dropped rather than guessed.

Texture assets are exported as UE object paths unless the supplied texture map
contains their source file paths. This makes a pull -> push round-trip possible
while still allowing the MaterialForge preview to use local PNG/HDR files.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Optional

try:
    import unreal  # type: ignore
except ImportError:  # Allows --help / --check outside the editor.
    unreal = None  # type: ignore


SCHEMA_ID = "materialforge.ue5.material"
SCHEMA_VERSION = 1


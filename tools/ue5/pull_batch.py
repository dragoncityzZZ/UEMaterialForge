#!/usr/bin/env python3
"""Batch UE5 -> MaterialForge pull bridge.

Enumerates materials under a UE content folder and writes one MaterialForge JSON
per material, plus a `batch_pull_manifest.json` summary.

    py "C:/path/to/tools/ue5/pull_batch.py" \
       --folder /Game/Materials \
       --out-dir "C:/path/to/pulled_materials" \
       --catalog "C:/path/to/tools/ue5/node_catalog.json"
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

try:
    import unreal  # type: ignore
except ImportError:  # Allows --dry-run outside the editor.
    unreal = None  # type: ignore

import pull_material_graph as puller


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Batch pull UE5 materials into MaterialForge JSON.")
    parser.add_argument("--folder", required=True,
                        help="UE content folder, e.g. /Game/Materials.")
    parser.add_argument("--out-dir", required=True,
                        help="Local directory for pulled JSON files.")
    parser.add_argument("--catalog",
                        default=str(Path(__file__).with_name("node_catalog.json")),
                        help="node_catalog.json generated by MaterialForge.")
    parser.add_argument("--texture-map", default=None,
                        help="Optional texture map JSON used in reverse.")
    parser.add_argument("--dry-run", action="store_true",
                        help="List materials without writing JSON.")
    return parser.parse_args()


def list_material_paths(folder: str) -> list[str]:
    if unreal is None:
        return []
    try:
        assets = unreal.EditorAssetLibrary.list_assets(folder, recursive=True,
                                                       include_folder=False)
    except Exception:
        return []
    result = []
    for asset_path in assets:
        try:
            asset = unreal.EditorAssetLibrary.load_asset(asset_path)
            if isinstance(asset, unreal.Material):
                result.append(str(asset_path))
        except Exception:
            continue
    return result


def main() -> int:
    args = parse_args()
    out_dir = Path(args.out_dir).expanduser().resolve()
    if not args.dry_run:
        out_dir.mkdir(parents=True, exist_ok=True)

    if unreal is None:
        if args.dry_run:
            puller.load_catalog(args.catalog)
            print(f"Dry run: UE runtime unavailable; would pull materials under {args.folder}.")
            return 0
        print("Batch pull requires the Unreal Editor Python environment.", file=sys.stderr)
        return 3

    materials = list_material_paths(args.folder)
    if not materials:
        print(f"No materials found under {args.folder}.")
        return 1

    records = []
    failures = 0
    for index, asset_path in enumerate(materials):
        name = asset_path.rsplit("/", 1)[-1] or f"Material_{index}"
        output = out_dir / f"{name}.json"
        print(f"[{index + 1}/{len(materials)}] {asset_path} -> {output}")
        if args.dry_run:
            records.append({"material": asset_path, "output": str(output), "ok": True})
            continue
        try:
            rc = puller.pull(asset_path, str(output), args.catalog, args.texture_map, False)
            records.append({"material": asset_path, "output": str(output), "ok": rc == 0})
            if rc != 0:
                failures += 1
        except Exception as exc:  # noqa: BLE001
            print(f"Pull failed: {exc}")
            records.append({"material": asset_path, "output": str(output), "ok": False,
                            "error": str(exc)})
            failures += 1

    manifest = {
        "schema": "materialforge.ue5.batch_pull",
        "version": 1,
        "sourceFolder": args.folder,
        "materials": records,
    }
    if not args.dry_run:
        (out_dir / "batch_pull_manifest.json").write_text(
            json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Pull complete: {len(records) - failures} succeeded, {failures} failed.")
    return 0 if failures == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
